% Problem 5.25 b
% Design lead compensator Dc(s) = k * (s+z) / (s+p)
% Requirement: s = -1 +- j * sqrt(3)

clear; clc;
wn = 2;
zeta = 0.5;
s = tf('s');
G = 1/(s*(s+1));
figure(1);

% % Step 2 - Plot uncompensated root locus
rlocus(G);
title('Uncompensated Root Locus');

% % Step 3 - can't meet specs with uncompensated system, so pick starting
% % values for lead compensator

z_lead = wn/6.25; % Rule of thumb: initially 25% of natural frequency.
p_lead = 4*z_lead; % Rule of thumb: initially placing pole at 10*z;
D_lead = (s + z_lead)/(s + p_lead);

figure(2);

% % Step 4 - Examine root locus and see if we can place the poles somewhere
% % where the specs will be met.
rlocus(D_lead*G)

% Step 5 - Select K value
K = 3.2653;


% This portion was generated by AI to graph the point nicely
% Find the closed-loop poles
closed_loop_poles = pole(feedback(K * D_lead * G, 1));

% Plot the marker first
figure(2);
rlocus(D_lead * G);
sgrid(zeta, wn);
hold on;
h = plot(real(closed_loop_poles(1)), imag(closed_loop_poles(1)), 'ro', 'MarkerSize', 8, 'LineWidth', 2);

% Automatically generate the text data tip on the plot
row = dataTipTextRow('Gain', repmat(K, size(closed_loop_poles(1))));
row2 = dataTipTextRow('Pole', closed_loop_poles(1));
h.DataTipTemplate.DataTipRows(end+1) = row;
h.DataTipTemplate.DataTipRows(end+1) = row2;

% Create the permanent data tip box at that coordinate
dt = datatip(h, real(closed_loop_poles(1)), imag(closed_loop_poles(1)));

hold off;






